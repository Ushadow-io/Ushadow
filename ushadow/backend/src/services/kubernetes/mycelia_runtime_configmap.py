"""
Mycelia frontend runtime ConfigMap — deploy-time injection of browser settings.

Generates the ConfigMap whose init.js the Mycelia SPA loads on every page
load (via a `<script src="/init.js">` tag injected by the frontend's vite
transformIndexHtml plugin). The script force-overwrites
`mycelia-settings.apiEndpoint` in localStorage and seeds clientId/clientSecret
when missing.

Why deploy-time generation: the public backend URL is per-environment (each
deployment has its own Tailscale Serve hostname). Baking it into the frontend
image is impossible; ushadow's settings store is the source of truth.

Reads MYCELIA_BACKEND_PUBLIC_URL / MYCELIA_CLIENT_ID / MYCELIA_TOKEN from the
service's resolved env vars. Skips generation when the public URL is blank —
the bundled public/init.js no-op in the frontend image then runs instead,
which is correct for same-origin deployments.
"""

import json
from typing import Any, Dict, List, Optional, Tuple

from src.utils.logging import get_logger

logger = get_logger(__name__, prefix="MyceliaRuntime")


CONFIGMAP_NAME = "mycelia-frontend-runtime"
VOLUME_NAME = "mycelia-runtime-config"
HTML_ROOT = "/usr/share/nginx/html"


def _render_init_js(backend_public_url: str, client_id: str, client_secret: str) -> str:
    """Render the init.js content the SPA loads before its main bundle.

    Force-overwrites apiEndpoint (container-owned); seeds clientId/clientSecret
    only when localStorage is missing them so user-supplied tokens survive.
    Also supports the #inject= fragment for cross-origin credential resets.
    """
    config = {
        "apiEndpoint": backend_public_url,
        "clientId": client_id,
        "clientSecret": client_secret,
    }
    config_json = json.dumps(config)

    return f"""// Mycelia frontend runtime config — generated by ushadow at deploy time.
// DO NOT hand-edit the rendered ConfigMap; change ushadow settings instead
// (mycelia.backend_public_url, api_keys.mycelia_client_id, api_keys.mycelia_token).
(function() {{
  var STORE_KEY = 'mycelia-settings';
  var CONFIG = {config_json};

  // (1) Cross-origin credential reset via #inject= fragment.
  // Ushadow's "Reset Mycelia login" button opens this app with
  //   #inject=<base64(JSON{{apiEndpoint,clientId,clientSecret}})>
  // The fragment is client-only (never sent to the server). Force-overwrite
  // localStorage, strip the fragment, and reload so the store rehydrates
  // from the fresh credentials before anything reads it.
  var m = location.hash.match(/[#&]inject=([^&]+)/);
  if (m) {{
    try {{
      var injected = JSON.parse(atob(decodeURIComponent(m[1])));
      localStorage.setItem(STORE_KEY, JSON.stringify({{state: injected, version: 0}}));
      console.log('[init.js] Overwrote mycelia settings from #inject= payload');
    }} catch (e) {{
      console.error('[init.js] Failed to parse #inject= payload', e);
    }}
    history.replaceState(null, '', location.pathname + location.search);
    location.reload();
    return;
  }}

  // (2) Force-overwrite apiEndpoint (container-owned); seed-if-empty for creds.
  // The endpoint must match the deployed backend — drift causes 405s on
  // /oauth/token and /api/* because the SPA hits the frontend's host
  // instead of the backend's. Creds are seed-if-empty so user-supplied
  // tokens survive across deploys.
  var existing = null;
  try {{ existing = JSON.parse(localStorage.getItem(STORE_KEY)); }} catch(e) {{}}

  var settings = (existing && existing.state) ? existing.state : {{}};
  var changed = false;

  if (settings.apiEndpoint !== CONFIG.apiEndpoint) {{
    settings.apiEndpoint = CONFIG.apiEndpoint;
    changed = true;
  }}
  if (!settings.clientId) {{
    settings.clientId = CONFIG.clientId;
    changed = true;
  }}
  if (!settings.clientSecret) {{
    settings.clientSecret = CONFIG.clientSecret;
    changed = true;
  }}

  if (changed) {{
    localStorage.setItem(STORE_KEY, JSON.stringify({{
      state: settings,
      version: (existing && typeof existing.version === 'number') ? existing.version : 0
    }}));
    console.log('[init.js] Synced mycelia settings from container config');
  }}
}})();
"""


def build_runtime_configmap(
    env_vars: Dict[str, str],
    namespace: str,
    labels: Dict[str, str],
) -> Optional[Dict[str, Any]]:
    """Build the mycelia-frontend-runtime ConfigMap from resolved env vars.

    Returns None when MYCELIA_BACKEND_PUBLIC_URL is blank — callers should
    skip the runtime mount in that case, letting the bundled public/init.js
    no-op (or whatever the frontend image ships) take over.
    """
    backend_url = (env_vars.get("MYCELIA_BACKEND_PUBLIC_URL") or "").strip()
    if not backend_url:
        logger.info(
            "MYCELIA_BACKEND_PUBLIC_URL not set — skipping runtime ConfigMap. "
            "Bundled public/init.js no-op will run instead."
        )
        return None

    client_id = (env_vars.get("MYCELIA_CLIENT_ID") or "").strip()
    client_secret = (env_vars.get("MYCELIA_TOKEN") or "").strip()
    if not client_id or not client_secret or client_id == "none" or client_secret == "none":
        logger.warning(
            "MYCELIA_CLIENT_ID/MYCELIA_TOKEN not provisioned — runtime ConfigMap "
            "will seed empty credentials, SPA will fall back to its setup flow."
        )

    return {
        "apiVersion": "v1",
        "kind": "ConfigMap",
        "metadata": {
            "name": CONFIGMAP_NAME,
            "namespace": namespace,
            "labels": labels,
        },
        "data": {
            "init.js": _render_init_js(backend_url, client_id, client_secret),
        },
    }


def runtime_volume_specs() -> Tuple[Dict[str, Any], List[Dict[str, Any]]]:
    """Return (volume_spec, volume_mounts) to overlay /init.js with the ConfigMap.

    The mount uses subPath so it lands as a single file (not a dir) at
    /usr/share/nginx/html/init.js, overlaying the bundled public/init.js.
    The vite transformIndexHtml plugin in the frontend ensures index.html
    includes `<script src="/init.js">`, so the mounted file actually runs.
    """
    volume = {
        "name": VOLUME_NAME,
        "configMap": {"name": CONFIGMAP_NAME},
    }
    mounts = [
        {
            "name": VOLUME_NAME,
            "mountPath": f"{HTML_ROOT}/init.js",
            "subPath": "init.js",
            "readOnly": True,
        },
    ]
    return volume, mounts
